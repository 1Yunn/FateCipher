/** 生成结构化回复：返回 { thinking, content } 两部分 */
export function buildReply(input: string, ctx: AskContext): { thinking: string; content: string } {
  const topic = detectTopic(input);
  const sections = splitStructured(topic, ctx);

  // 前 6 段 → 思考块内容
  const thinkingSections = REPLY_SECTIONS.slice(0, 6);
  const thinking = thinkingSections
    .map((s) => {
      const content = sections[s.key] ?? "";
      return `## ${s.title}\n${content}`;
    })
    .join("\n\n");

  // 第 7 段（行动建议）→ 正文大号
  const content = sections["action"] ?? "";

  return { thinking, content };
}
